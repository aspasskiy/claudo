@testable import ClaudoCore
import XCTest

/// Transcript parsing on hand-written jsonl: pasted prompts, tool traffic, what isn't a prompt.
final class SessionsTests: XCTestCase {
    func testAPasteKeepsTheOwnersWordsFirstAndDropsTheTags() {
        let letter = "<pasted_content id=\"b313\">\nHi,\nStarting Monday calls will be rejected.\n</pasted_content id=\"b313\">\n\n got this letter, what does it mean?"
        XCTAssertEqual(Sessions.prompt(letter), "got this letter, what does it mean?\nHi,\nStarting Monday calls will be rejected.")
        XCTAssertEqual(Sessions.prompt("<pasted_content id=\"a\">\nbuild failed\n</pasted_content id=\"a\">"), "build failed")
        XCTAssertEqual(Sessions.unwrapPastes("<pasted_content id=\"1\">A</pasted_content id=\"1\"> and <pasted_content id=\"2\">B"),
                       "and\nA\nB", "two pastes, the second one never closed")
        XCTAssertNil(Sessions.prompt("<pasted_content id=\"x\">\n</pasted_content id=\"x\">"))
    }

    func testTagsAndInterruptionsAreNotPrompts() {
        XCTAssertNil(Sessions.prompt("<command-name>/clear</command-name>"))
        XCTAssertNil(Sessions.prompt("<bash-input>ls</bash-input>"))
        XCTAssertNil(Sessions.prompt("<task-notification>done</task-notification>"))
        XCTAssertNil(Sessions.prompt("[Request interrupted by user]"))
        XCTAssertNil(Sessions.prompt("Caveat: the messages below were generated by the user"))
        XCTAssertNil(Sessions.prompt(""))
        XCTAssertEqual(Sessions.prompt("do it"), "do it")
    }

    func testAPasteOnlySessionIsSeenAndToolTrafficMovesItsLastRecord() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("claudo-tests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let paste = #"<pasted_content id=\"a1\">\nAcme will reject unverified caller IDs.\n</pasted_content id=\"a1\">\n\n what does it mean?"#
        let lines = [
            #"{"type":"ai-title","aiTitle":"The Acme letter"}"#,
            #"{"type":"user","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:00:00.000Z","message":{"role":"user","content":"\#(paste)"}}"#,
            #"{"type":"assistant","timestamp":"2026-10-18T08:00:30.000Z","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{}}]}}"#,
            #"{"type":"user","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:05:00.000Z","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]}}"#,
        ]
        let url = dir.appendingPathComponent("4f4b09d0-0000-4000-8000-00000000000a.jsonl")
        try lines.joined(separator: "\n").write(to: url, atomically: true, encoding: .utf8)

        let s = try XCTUnwrap(Sessions.parse(url, since: F.now - 30 * F.day))
        XCTAssertEqual(s.id, "4f4b09d0-0000-4000-8000-00000000000a")
        XCTAssertEqual(s.title, "The Acme letter")
        XCTAssertEqual(s.prompts, ["what does it mean?\nAcme will reject unverified caller IDs."])
        XCTAssertTrue(s.awaitingReply)
        let iso = ISO8601DateFormatter()
        XCTAssertEqual(s.end, iso.date(from: "2026-10-18T08:00:00Z"))
        XCTAssertEqual(s.lastRecord, iso.date(from: "2026-10-18T08:05:00Z"), "tool traffic counts as activity")
        XCTAssertTrue(s.turnOpen)
    }

    /// A turn: the prompt opens it, a text on the way doesn't close it while tools follow, a final text or
    /// an interrupt does.
    func testATurnStaysOpenUntilAFinalTextOrAnInterrupt() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("claudo-tests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        func record(_ type: String, _ minute: Int, _ content: String) -> String {
            #"{"type":"\#(type)","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:\#(String(format: "%02d", minute)):00.000Z","message":{"role":"\#(type)","content":\#(content)}}"#
        }
        let prompt = record("user", 0, #""fix the payments""#)
        let checking = record("assistant", 1, #"[{"type":"text","text":"Checking the worker."}]"#)
        let tool = record("assistant", 2, #"[{"type":"tool_use","id":"t1","name":"Bash","input":{}}]"#)
        let result = record("user", 3, #"[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]"#)
        let done = record("assistant", 4, #"[{"type":"text","text":"Done: pushed."}]"#)
        let stop = record("user", 5, #"[{"type":"text","text":"[Request interrupted by user for tool use]"}]"#)
        func parse(_ lines: [String]) throws -> SessionDigest {
            let url = dir.appendingPathComponent("\(UUID().uuidString).jsonl")
            try lines.joined(separator: "\n").write(to: url, atomically: true, encoding: .utf8)
            return try XCTUnwrap(Sessions.parse(url, since: F.now - 30 * F.day))
        }

        let running = try parse([prompt, checking, tool, result])
        XCTAssertFalse(running.awaitingReply, "it has answered something…")
        XCTAssertTrue(running.turnOpen, "…and is still at work")
        XCTAssertEqual(running.lastReply, "Checking the worker.")
        XCTAssertFalse(try parse([prompt, checking, tool, result, done]).turnOpen)
        let interrupted = try parse([prompt, checking, tool, stop])
        XCTAssertFalse(interrupted.turnOpen)
        XCTAssertEqual(interrupted.prompts, ["fix the payments"], "an interrupt isn't a prompt")
        XCTAssertTrue(try parse([prompt]).turnOpen)
    }

    /// What the owner types while an agent works is a queued attachment, not a user record; other sessions'
    /// messages come in the same way and aren't theirs.
    func testWordsQueuedWhileAnAgentWorksArePrompts() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("claudo-tests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        func queued(_ minute: Int, _ text: String, kind: String = "human") -> String {
            #"{"type":"attachment","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:\#(String(format: "%02d", minute)):00.000Z","attachment":{"type":"queued_command","prompt":"\#(text)","commandMode":"prompt","origin":{"kind":"\#(kind)"}}}"#
        }
        let lines = [
            #"{"type":"user","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:00:00.000Z","message":{"role":"user","content":"fix the payments"}}"#,
            #"{"type":"assistant","timestamp":"2026-10-18T08:01:00.000Z","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{}}]}}"#,
            queued(2, "never mind, leave prod alone"),
            queued(3, "<agent-message from=\"a1\">done</agent-message>", kind: "peer"),
            queued(4, "and check the logs"),
            #"{"type":"user","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:05:00.000Z","message":{"role":"user","content":"and check the logs"}}"#,
            #"{"type":"assistant","timestamp":"2026-10-18T08:06:00.000Z","message":{"role":"assistant","content":[{"type":"text","text":"Stopped."}]}}"#,
        ]
        let url = dir.appendingPathComponent("\(UUID().uuidString).jsonl")
        try lines.joined(separator: "\n").write(to: url, atomically: true, encoding: .utf8)

        let s = try XCTUnwrap(Sessions.parse(url, since: F.now - 30 * F.day))
        XCTAssertEqual(s.prompts, ["fix the payments", "never mind, leave prod alone", "and check the logs"],
                       "the peer message is out, the queued prompt sent again counts once")
        XCTAssertEqual(s.queuedCount, 1)
        XCTAssertEqual(s.typedPromptCount, 2)
        XCTAssertEqual(Planner.lastWords(s), "\"never mind, leave prod alone\" → \"and check the logs\"")
        XCTAssertFalse(s.turnOpen)
    }

    /// Claude Code's recap stands for the session while the owner hasn't written since; its config hint goes.
    func testARecapCountsOnlyAfterTheLastPrompt() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("claudo-tests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        func prompt(_ minute: Int, _ text: String) -> String {
            #"{"type":"user","cwd":"/Users/me/dev/app","timestamp":"2026-10-18T08:\#(String(format: "%02d", minute)):00.000Z","message":{"role":"user","content":"\#(text)"}}"#
        }
        let reply = #"{"type":"assistant","timestamp":"2026-10-18T08:01:00.000Z","message":{"role":"assistant","content":[{"type":"text","text":"Done, waiting for your key."}]}}"#
        let recap = #"{"type":"system","subtype":"away_summary","content":"You asked to fix the payments: the worker is fixed. Next it needs your API key. (disable recaps in /config)","timestamp":"2026-10-18T08:05:00.000Z"}"#
        func parse(_ lines: [String]) throws -> SessionDigest {
            let url = dir.appendingPathComponent("\(UUID().uuidString).jsonl")
            try lines.joined(separator: "\n").write(to: url, atomically: true, encoding: .utf8)
            return try XCTUnwrap(Sessions.parse(url, since: F.now - 30 * F.day))
        }

        let s = try parse([prompt(0, "fix the payments"), reply, recap])
        XCTAssertEqual(s.recap, "You asked to fix the payments: the worker is fixed. Next it needs your API key.")
        XCTAssertTrue(Planner.detailBlock(s, now: F.now).contains("Claude Code recap: You asked to fix the payments"))
        XCTAssertTrue(Planner.briefBlock(s, now: F.now).contains("Result (Claude Code recap): You asked"))
        XCTAssertFalse(Planner.briefBlock(s, now: F.now).contains("waiting for your key"), "the recap replaces the reply's tail")
        XCTAssertTrue(s.rawBlock.contains("Claude Code recap:"), "the summarizer reads it too")
        XCTAssertNil(try parse([prompt(0, "fix the payments"), reply, recap, prompt(10, "now deploy")]).recap,
                     "the owner wrote after it: it describes a state they have moved past")
    }
}
